def fixture_manifest(domain):
    return [
        {"id": identifier, "description": text,
         "sha256": hashlib.sha256((identifier + "\n" + text).encode("utf-8")).hexdigest(),
         "attribution": ATTRIBUTION[domain]}
        for identifier, text in FIXTURES[domain]
    ]


def check_fixture_manifest():
    manifest = {domain: fixture_manifest(domain) for domain in DOMAINS}
    digest = hashlib.sha256(json.dumps(
        manifest, sort_keys=True, separators=(",", ":")).encode()).hexdigest()
    if digest != FIXTURE_MANIFEST_SHA256:
        raise AssertionError("fixed domain fixture/attribution manifest changed")
    return manifest


def compact_tokens(text, vocabulary=8):
    data = text.encode("utf-8")
    return [sum(data[len(data) * i // 3:len(data) * (i + 1) // 3]) % vocabulary
            for i in range(3)]


def benchmark_images(path, fixture, geometry, seed, thinking):
    path.mkdir(exist_ok=False)
    image = Image(geometry, seed)
    decoder = Decoder(image)
    tables = image.memory_tables()
    tables.update({name: [] for name in (
        "expected-scratch", "expected-initial", "expected-key", "expected-value",
        "expected-logits", "host-token", "host-phase", "expected-token", "eval-token",
        "host-position", "expected-count", "expected-frames", "expected-committed",
        "draft-count", "draft-token", "draft-parent")})
    evaluations, transactions = [], []

    def evaluate(token, position):
        result = decoder.evaluate(token, position)
        tables["eval-token"].append(token)
        tables["expected-initial"].extend(result["initial"])
        tables["expected-key"].extend(result["keys"][0])
        tables["expected-value"].extend(result["values"][0])
        tables["expected-logits"].extend(result["logits"])
        scratch = [0] * (15 * geometry.maximum)
        for slot, data in result["stages"][0].items():
            scratch[slot * geometry.maximum:slot * geometry.maximum + len(data)] = data
        tables["expected-scratch"].extend(scratch)
        evaluations.append({"token": token, "position": position, "argmax": result["argmax"],
                            "logits_sha256": hashlib.sha256(
                                b"".join(x.to_bytes(4, "little") for x in result["logits"])).hexdigest()})
        return result["argmax"]

    def transaction(token, position, phase, generated, nodes=(), parents=()):
        tables["host-token"].append(token)
        tables["host-position"].append(position)
        tables["host-phase"].append(phase)
        tables["expected-count"].append(len(generated))
        tables["expected-frames"].append(len(evaluations))
        tables["expected-token"].append(generated[-1] if generated else 0)
        tables["expected-committed"].extend(list(generated) + [0] * (5 - len(generated)))
        tables["draft-count"].append(len(nodes))
        tables["draft-token"].append(fp.pack(list(nodes) + [0] * (4 - len(nodes)), 32))
        tables["draft-parent"].append(fp.pack(list(parents) + [0] * (4 - len(parents)), 3))
        transactions.append({"token": token, "position": position, "phase": phase,
                             "generated": list(generated), "nodes": list(nodes),
                             "parents": list(parents)})

    prompt = compact_tokens(fixture["description"], geometry.vocabulary)
    for position, token in enumerate(prompt):
        target = evaluate(token, position)
        transaction(token, position, 0, [])
    # First decode resubmits the previous context's greedy token.
    token, position, generated_count = target, len(prompt), 0
    while generated_count < 6:
        target = evaluate(token, position)
        generated, nodes, parents = [target], [], []
        if thinking:
            if generated_count == 0:
                # Four accepted ancestors plus a deferred bonus.
                for node in range(4):
                    nodes.append(generated[-1])
                    parents.append(4 if node == 0 else node - 1)
                    generated.append(evaluate(generated[-1], position + len(generated)))
            else:
                nodes, parents = [(target + 1) % geometry.vocabulary], [4]
        transaction(token, position, 1, generated, nodes, parents)
        generated_count += len(generated)
        position += len(generated)
        token = generated[-1]
    if len(evaluations) != 9 or generated_count != 6:
        raise AssertionError("benchmark must compare three prompt and six decoding frames")
    # Fixed dimensions allow one compiled bench/family for both modes and cases.
    for name in ("host-token", "host-position", "host-phase", "expected-count",
                 "expected-frames", "expected-token", "expected-committed",
                 "draft-count", "draft-token", "draft-parent"):
        extent = 5 if name == "expected-committed" else 1
        tables[name].extend([0] * ((9 - len(transactions)) * extent))
    for name, values in tables.items():
        width = 32 if name == "draft-token" else 3 if name == "draft-parent" else 8
        with (path / f"{name}.hex").open("x") as output:
            output.writelines(f"{value:0{width}x}\n" for value in values)
    return prompt, evaluations, transactions


def benchmark_bench():
    text = speculative_bench()
    text = replace_once(text, "parameter H=8,I=8,QH=2,KH=1,D=8,V=8,M=16,N=1,T=3;",
                        "parameter H=8,I=8,QH=2,KH=1,D=8,V=8,M=16,N=9,T=9,P=3;")
    text = replace_once(text, "reg csr_valid=0,configured_mode=0;",
                        "reg csr_valid=0,configured_mode=0;\n"
                        "  integer desired_mode=0,actual_transactions=0;\n"
                        "  integer previous_done_cycle=0,previous_requests=0;")
    text = replace_once(text, "anvil_qn1_top #(.COMPACT(1)", "anvil_qn1_top #(.PROFILE(P),.COMPACT(1)")
    text = replace_once(text, ".csr_wdata(32'd1)", ".csr_wdata(desired_mode)")
    text = replace_once(text, "configured_mode=1;", "configured_mode=desired_mode[0];")
    text = replace_once(text, "draft_valid=!draft_seen;",
                        "draft_valid=configured_mode && host_phases[active_tx]==1 && !draft_seen;")
    text = replace_once(text, "for (c=0;c<T;c=c+1) begin",
                        'if (!$value$plusargs("transactions=%d",actual_transactions) ||\n'
                        '        !$value$plusargs("thinking=%d",desired_mode) ||\n'
                        '        actual_transactions<1 || actual_transactions>T ||\n'
                        '        desired_mode<0 || desired_mode>1) $fatal(1,"BENCH_ARGS");\n'
                        "    for (c=0;c<actual_transactions;c=c+1) begin")
    text = replace_once(text, "completed=completed+1;",
                        '$display("BENCH_TX tx=%0d phase=%0d mode=%0d cycles=%0d tokens=%0d requests=%0d",\n'
                        "          active_tx,host_phases[active_tx],configured_mode,\n"
                        "          cycle-previous_done_cycle,expected_counts[active_tx],\n"
                        "          req_count-previous_requests);\n"
                        "        previous_done_cycle=cycle;previous_requests=req_count;\n"
                        "        completed=completed+1;")
    return text


def run_benchmark_case(run, fixture, family, seed, thinking, compiled=None):
    manifest = check_fixture_manifest()
    if fixture not in [record for records in manifest.values() for record in records]:
        raise AssertionError("benchmark case is not an immutable real-domain fixture")
    geometry = Geometry(q_heads=4 if family == 3 else 2)
    images = run.path / "checkpoint-images"
    prompt, evaluations, transactions = benchmark_images(images, fixture, geometry, seed, thinking)
    bench = run.path / "benchmark_tb.sv"
    bench.write_text(benchmark_bench())
    parameters = {"P": family, "QH": geometry.q_heads}
    binding = {"parameters": parameters, "bench_sha256": hashlib.sha256(bench.read_bytes()).hexdigest(),
               "rtl_sha256": {k: v for k, v in run.hashes.items()
                              if k.startswith("rtl/anvil_qn1_")},
               "tool_versions": run.tool_versions}
    if compiled is not None and compiled["binding"] != binding:
        raise AssertionError("benchmark build source/geometry/tool mismatch")
    if compiled is None:
        objects = run.path / "obj-benchmark"
        sources = [relative(p) for p in sorted((ROOT / "rtl").glob("anvil_qn1_*.sv"))]
        run.execute(["verilator", "--binary", "--timing", "-Wno-fatal", "-j", "2",
                     "--top-module", "top_tb", *[f"-G{k}={v}" for k, v in parameters.items()],
                     "--Mdir", relative(objects), "-o", "simulate", *sources, relative(bench)],
                    "benchmark-compile")
        compiled = {"binary": relative(objects / "simulate"), "binding": binding}
    output = run.execute([compiled["binary"], f"+images={relative(images)}",
                          f"+transactions={len(transactions)}", f"+thinking={int(thinking)}"],
                         "benchmark-simulation")
    counts = [list(map(int, row)) for row in re.findall(
        r"^BENCH_TX tx=(\d+) phase=(\d+) mode=(\d+) cycles=(\d+) tokens=(\d+) requests=(\d+)$",
        output, re.M)]
    if len(counts) != len(transactions):
        raise AssertionError("missing benchmark transaction measurements")
    for expected_index, (row, transaction) in enumerate(zip(counts, transactions)):
        index, phase, mode, cycles, tokens, requests = row
        if (index != expected_index or phase != transaction["phase"] or
                mode != int(thinking and index >= 1) or cycles <= 0 or requests <= 0 or
                tokens != len(transaction["generated"])):
            raise AssertionError(f"benchmark measurement mismatch: {row}")
    expected = (f"SUMMARY transactions={len(transactions)} frames=9 logits={9*geometry.vocabulary} "
                f"key_writes={9*geometry.kv_dimension} value_writes={9*geometry.kv_dimension}")
    if output.count(expected) != 1:
        raise AssertionError("missing benchmark full-frame/KV comparisons")
    decode = [r for r in counts if r[1] == 1]
    result = {"fixture": fixture, "fixture_manifest_sha256": FIXTURE_MANIFEST_SHA256,
              "family": family, "geometry": vars(geometry),
              "prompt_tokens": prompt, "seed": seed, "thinking": thinking,
              "evaluations": evaluations, "transactions": transactions,
              "measurements": counts, "decode_cycles": sum(r[3] for r in decode),
              "generated_tokens": sum(r[4] for r in decode),
              "compared_frames": 9, "compared_logit_words": 9 * geometry.vocabulary,
              "clock_hz_assumed_for_conversion": 100000000,
              "measurement_scope": "stall-inclusive simulated cycles; no physical clock claim",
              "compiled": compiled}
    if result["generated_tokens"] != 6 or len(evaluations) - len(prompt) != 6:
        raise AssertionError("missing six compared decode steps")
    (run.path / "benchmark-reference.json").write_text(json.dumps(result, indent=2) + "\n")
    return result


def run_benchmark(run, domain):
    if domain not in DOMAINS:
        raise ValueError(f"unknown benchmark domain: {domain}")
    check_fixture_manifest()
    results, builds = [], {}
    for index, fixture in enumerate(fixture_manifest(domain)):
        family = (1, 2, 3, 3)[index]
        for thinking in (False, True):
            def operation(child, fixture=fixture, family=family, index=index, thinking=thinking):
                result = run_benchmark_case(child, fixture, family, (17, 89, 203, 17)[index],
                                            thinking, builds.get(family))
                builds[family] = result["compiled"]
                return result
            results.append(run.component(f"benchmark-{domain}-case{index}-mode{int(thinking)}",
                                         operation))
    if (len(results) != 8 or {r["family"] for r in results} != {1, 2, 3} or
            {r["geometry"]["q_heads"] for r in results} != {2, 4}):
        raise AssertionError("missing domain/family/mode benchmark coverage")
    return {"domain": domain, "scope": __doc__, "cases": results,
            "fixture_manifest_sha256": FIXTURE_MANIFEST_SHA256,
            "fixture_count": 4, "compared_frames": sum(r["compared_frames"] for r in results),
            "compared_logit_words": sum(r["compared_logit_words"] for r in results),
            "modes": {str(int(mode)): {
                "generated_tokens": sum(r["generated_tokens"] for r in results if r["thinking"] == mode),
                "decode_cycles": sum(r["decode_cycles"] for r in results if r["thinking"] == mode),
            } for mode in (False, True)}}
